#include "../Common/Include/tiremo_systick.h"
#include "../Common/Include/tiremo_debug.h"
#include "../Drivers/esp32/Include/tiremo_esp32.h"

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <string.h>

/* Generated by cmake/embed_pem.cmake from the PEM files under Sw/certs/
 * at build time -- see CMakeLists.txt's embed_pem() calls. Self-signed
 * test PEM files, not real AWS credentials; Tutorial 03 replaces the
 * content of these same three files with the real thing. */
extern const unsigned char g_rootCaPem[];
extern const size_t g_rootCaPem_len;
extern const unsigned char g_clientCertPem[];
extern const size_t g_clientCertPem_len;
extern const unsigned char g_clientKeyPem[];
extern const size_t g_clientKeyPem_len;

/** @brief Large enough for the biggest test file here (client_key.pem,
 *  ~1.7 KB) with headroom; a real AWS device cert/key is a similar size. */
#define READ_BUF_SIZE (2048U)

static void Hang(const char *pWhy)
{
    TIREMO_LOG_ERROR("%s", pWhy);
    for (;;)
    {
    }
}

/**
 * @brief Full write -> read-back -> byte-compare -> erase -> read-should-fail
 *        cycle for one credential slot.
 *
 * @return true when every step behaved as expected.
 */
static bool TestSlot(TIREMO_ESP32_CredSlot_t slot, const char *pName,
                     const unsigned char *pData, uint32_t length)
{
    static uint8_t s_readBuf[READ_BUF_SIZE];
    uint32_t readLen = 0U;
    bool ok = true;

    TIREMO_LOG_INFO("%s: writing %lu bytes...", pName, (unsigned long)length);
    if (!TIREMO_ESP32_CredWrite(slot, pData, length))
    {
        TIREMO_LOG_ERROR("%s: write failed", pName);
        return false;
    }

    memset(s_readBuf, 0, sizeof(s_readBuf));
    if (!TIREMO_ESP32_CredRead(slot, s_readBuf, sizeof(s_readBuf), &readLen))
    {
        TIREMO_LOG_ERROR("%s: read-back failed", pName);
        return false;
    }

    if ((readLen != length) || (memcmp(s_readBuf, pData, length) != 0))
    {
        TIREMO_LOG_ERROR("%s: read-back MISMATCH (wrote %lu bytes, read %lu)",
                         pName, (unsigned long)length, (unsigned long)readLen);
        ok = false;
    }
    else
    {
        TIREMO_LOG_INFO("%s: read-back matches byte-for-byte (%lu bytes)",
                        pName, (unsigned long)readLen);
    }

    if (!TIREMO_ESP32_CredErase(slot))
    {
        TIREMO_LOG_ERROR("%s: erase failed", pName);
        return false;
    }
    TIREMO_LOG_INFO("%s: erased", pName);

    /* A read of an erased slot is expected to fail -- that failure IS
     * the pass condition here, not a real error. */
    if (TIREMO_ESP32_CredRead(slot, s_readBuf, sizeof(s_readBuf), &readLen))
    {
        TIREMO_LOG_ERROR("%s: read after erase unexpectedly SUCCEEDED", pName);
        ok = false;
    }
    else
    {
        TIREMO_LOG_INFO("%s: read after erase correctly failed (slot empty)",
                        pName);
    }

    return ok;
}

void PRV_USER_Code(void)
{
    bool rootCaOk;
    bool certOk;
    bool keyOk;

    (void)TIREMO_SysTick_Init();
    (void)TIREMO_Debug_Init();

    TIREMO_LOG_INFO("mTLS_Credentials_In_Module_NVS: boot");

    if (!TIREMO_ESP32_Init())
    {
        Hang("ESP32: transport init failed");
    }
    if (!TIREMO_ESP32_IsPresent())
    {
        Hang("ESP32: AT probe failed (no OK)");
    }
    if (!TIREMO_ESP32_DisableEcho())
    {
        Hang("ESP32: ATE0 failed");
    }

    rootCaOk = TestSlot(TIREMO_ESP32_CREDSLOT_ROOT_CA, "ROOT_CA",
                        g_rootCaPem, (uint32_t)g_rootCaPem_len);
    certOk = TestSlot(TIREMO_ESP32_CREDSLOT_CLIENT_CERT, "CLIENT_CERT",
                      g_clientCertPem, (uint32_t)g_clientCertPem_len);
    keyOk = TestSlot(TIREMO_ESP32_CREDSLOT_CLIENT_KEY, "CLIENT_KEY",
                     g_clientKeyPem, (uint32_t)g_clientKeyPem_len);

    if (rootCaOk && certOk && keyOk)
    {
        TIREMO_LOG_INFO("mTLS_Credentials_In_Module_NVS: ALL THREE SLOTS PASSED");
    }
    else
    {
        TIREMO_LOG_ERROR("mTLS_Credentials_In_Module_NVS: at least one slot FAILED "
                         "(root_ca=%s client_cert=%s client_key=%s)",
                         rootCaOk ? "ok" : "FAIL",
                         certOk ? "ok" : "FAIL",
                         keyOk ? "ok" : "FAIL");
    }

    for (;;)
    {
        TIREMO_SysTick_DelayMs(10000U);
        TIREMO_LOG_INFO("mTLS_Credentials_In_Module_NVS: idle (test already ran once at boot)");
    }
}
